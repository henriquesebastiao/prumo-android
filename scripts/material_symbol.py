#!/usr/bin/env python3
"""Generates Material Symbols Rounded icons as Android vector drawables in :core:designsystem.

Each NAME becomes res/drawable/ic_NAME.xml (outlined, weight 400, optical size 24, the design's
icons) and, with --filled, also ic_NAME_filled.xml. The SVGs come from Google Fonts' static icon
files (fonts.gstatic.com), the same drawing the design's icon font shows. Apache License 2.0.

Usage: scripts/material_symbol.py [--filled] NAME [NAME...]
Then add the icon to PrumoIcons (core/designsystem/.../component/PrumoIcons.kt).
"""

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "core" / "designsystem" / "src" / "main" / "res" / "drawable"
URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{style}/24px.svg"
# Icons that point somewhere: mirrored in right-to-left layouts.
MIRRORED = {"arrow_back", "arrow_forward", "chevron_left", "chevron_right", "login", "logout", "open_in_new"}

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}" ({variant}), Apache 2.0. Generated by scripts/material_symbol.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:autoMirrored="{mirrored}"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{path}" />
    </group>
</vector>
"""


def fetch(name, style):
    with urllib.request.urlopen(URL.format(name=name, style=style), timeout=30) as response:
        svg = response.read().decode()
    if 'viewBox="0 -960 960 960"' not in svg:
        raise SystemExit(f"{name}: unexpected viewBox")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        raise SystemExit(f"{name}: expected one path, found {len(paths)}")
    return paths[0]


def write(name, style, suffix, variant):
    path = fetch(name, style)
    text = TEMPLATE.format(
        name=name,
        variant=variant,
        mirrored="true" if name in MIRRORED else "false",
        path=path,
    )
    out = TARGET / f"ic_{name}{suffix}.xml"
    out.write_text(text, encoding="utf-8")
    print(f"  {out.relative_to(ROOT)}")


def main():
    args = sys.argv[1:]
    filled = "--filled" in args
    names = [a for a in args if not a.startswith("--")]
    if not names:
        raise SystemExit(__doc__)
    TARGET.mkdir(parents=True, exist_ok=True)
    for name in names:
        if not re.fullmatch(r"[a-z0-9_]+", name):
            raise SystemExit(f"{name}: not a Material Symbol name")
        write(name, "default", "", "outlined")
        if filled:
            write(name, "fill1", "_filled", "filled")


if __name__ == "__main__":
    main()
