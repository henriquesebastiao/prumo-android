// ─────────────────────────────────────────────────────────────
// Device frame — wraps everything
// ─────────────────────────────────────────────────────────────
// Edge-to-edge: status bar and gesture bar overlay the content; screens add
// their own 40px top / 24px bottom insets. `numpad` docks a numeric keyboard.
function AndroidDevice({
  children, width = 412, height = 892, dark = false,
  keyboard = false, numpad = false, bg,
}) {
  return (
    <div data-om-starter="android-frame" style={{
      width, height, borderRadius: 34, overflow: 'hidden', position: 'relative',
      background: bg || (dark ? '#0a0a0a' : '#ffffff'),
      border: `8px solid ${dark ? '#262626' : '#d4d4d4'}`,
      boxShadow: '0 24px 60px rgba(0,0,0,0.16)',
      display: 'flex', flexDirection: 'column', boxSizing: 'border-box',
    }}>
      <div style={{ flex: 1, minHeight: 0, position: 'relative', overflow: 'hidden' }}>
        {children}
      </div>
      {keyboard && <AndroidKeyboard />}
      {numpad && <AndroidNumpad dark={dark} />}
      <div style={{ position: 'absolute', top: 0, left: 0, right: 0, zIndex: 80, pointerEvents: 'none' }}><AndroidStatusBar dark={dark} /></div>
      <div style={{ position: 'absolute', bottom: 0, left: 0, right: 0, zIndex: 80, pointerEvents: 'none' }}><AndroidNavBar dark={dark} /></div>
    </div>
  );
}

// Numeric keyboard (Gboard number layout)
function AndroidNumpad({ dark = false }) {
  const bg = dark ? '#1a1a1a' : '#e5e5e5';
  const keyBg = dark ? '#262626' : '#ffffff';
  const fnBg = dark ? '#404040' : '#d4d4d4';
  const fg = dark ? '#f5f5f5' : '#111111';
  const icon = (n) => <span style={{ fontFamily: "'Material Symbols Rounded'", fontSize: 22, lineHeight: 1, width: 22, height: 22, overflow: 'hidden' }}>{n}</span>;
  const rows = [
    [['1'], ['2'], ['3'], ['−', 'fn']],
    [['4'], ['5'], ['6'], [icon('space_bar'), 'fn']],
    [['7'], ['8'], ['9'], [icon('backspace'), 'fn']],
    [[','], ['0'], ['.'], [icon('arrow_forward'), 'go']],
  ];
  return (
    <div style={{ background: bg, padding: '10px 8px 30px', display: 'flex', flexDirection: 'column', gap: 6 }}>
      {rows.map((r, i) => (
        <div key={i} style={{ display: 'flex', gap: 6 }}>
          {r.map(([l, t], j) => (
            <div key={j} style={{
              flex: t ? 0.8 : 1, height: 46, borderRadius: t === 'go' ? 100 : 8,
              background: t === 'go' ? fg : t ? fnBg : keyBg,
              color: t === 'go' ? bg : fg,
              display: 'flex', alignItems: 'center', justifyContent: 'center',
              fontFamily: 'Roboto, system-ui, sans-serif', fontSize: 22,
            }}>{l}</div>
          ))}
        </div>
      ))}
    </div>
  );
}

// ─────────────────────────────────────────────────────────────
// Keyboard — Gboard (Material 3)
// ─────────────────────────────────────────────────────────────
function AndroidKeyboard() {
  let _k = 0;
  const key = (l, { flex = 1, bg = MD_C.surface, r = 6, minW, fs = 21 } = {}) => (
    <div key={_k++} style={{
      height: 46, borderRadius: r, flex, minWidth: minW,
      background: bg, display: 'flex', alignItems: 'center', justifyContent: 'center',
      fontFamily: 'Roboto, system-ui', fontSize: fs,
      color: MD_C.onPrimaryContainer,
    }}>{l}</div>
  );
  const row = (keys, style = {}) => (
    <div style={{ display: 'flex', gap: 6, justifyContent: 'center', ...style }}>
      {keys.map(l => key(l))}
    </div>
  );
  return (
    <div style={{
      background: MD_C.inverseOnSurface, padding: '0 8px 8px',
      display: 'flex', flexDirection: 'column', gap: 4,
    }}>
      {/* navbar spacer (icons omitted) */}
      <div style={{ height: 44 }} />
      {/* key rows */}
      <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
        {row(['q','w','e','r','t','y','u','i','o','p'])}
        {row(['a','s','d','f','g','h','j','k','l'], { padding: '0 20px' })}
        <div style={{ display: 'flex', gap: 6 }}>
          {key('', { bg: MD_C.surfaceVariant })}
          <div style={{ display: 'flex', gap: 6, flex: 7, minWidth: 274 }}>
            {['z','x','c','v','b','n','m'].map(l => key(l))}
          </div>
          {key('', { bg: MD_C.surfaceVariant })}
        </div>
        <div style={{ display: 'flex', gap: 6 }}>
          {key('?123', { bg: MD_C.secondaryContainer, r: 100, minW: 58, fs: 14 })}
          {key(',', { bg: MD_C.surfaceVariant })}
          {key('', { flex: 3, minW: 154 })}
          {key('.', { bg: MD_C.surfaceVariant })}
          {key('', { bg: MD_C.primaryFixedDim, r: 100, minW: 58 })}
        </div>
      </div>
    </div>
  );
}

